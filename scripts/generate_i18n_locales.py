def write_json_files():
    total_files = 0
    all_locales = list(LOCALES.keys())
    if "en" not in all_locales:
        all_locales.insert(0, "en")
    
    for loc in all_locales:
        loc_dir = os.path.join(BASE_DIR, loc)
        os.makedirs(loc_dir, exist_ok=True)
        data = LOCALES.get(loc, EN_DATA)
        for ns in ["common", "navigation", "dashboard", "learning", "practice", "settings", "auth", "world", "errors"]:
            ns_dict = data.get(ns, EN_DATA[ns])
            # Ensure every single key from EN_DATA[ns] is present (fallback guarantee)
            full_ns_dict = {}
            for k, default_val in EN_DATA[ns].items():
                full_ns_dict[k] = ns_dict.get(k, default_val)
            
            filepath = os.path.join(loc_dir, f"{ns}.json")
            with open(filepath, "w", encoding="utf-8") as f:
                json.dump(full_ns_dict, f, ensure_ascii=False, indent=2)
            total_files += 1

    print(f"Successfully generated {total_files} i18n JSON files across {len(all_locales)} locales in {BASE_DIR}")

if __name__ == "__main__":
    write_json_files()
