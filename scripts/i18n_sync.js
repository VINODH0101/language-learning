// Process each locale
LOCALES.forEach(loc => {
  const dir = path.join(LOCALES_DIR, loc);
  if (!fs.existsSync(dir)) fs.mkdirSync(dir, { recursive: true });

  // 1. Write progress.json
  let pData = progressBase;
  if (loc === 'pt' || loc === 'pt-BR' || loc === 'pt-PT') pData = progressPt;
  else if (loc === 'es') pData = progressEs;
  fs.writeFileSync(path.join(dir, 'progress.json'), JSON.stringify(pData, null, 2) + '\n');

  // 2. Write admin.json
  let aData = adminBase;
  if (loc === 'pt' || loc === 'pt-BR' || loc === 'pt-PT') aData = adminPt;
  else if (loc === 'es') aData = adminEs;
  fs.writeFileSync(path.join(dir, 'admin.json'), JSON.stringify(aData, null, 2) + '\n');

  // 3. Extend practice.json
  const practicePath = path.join(dir, 'practice.json');
  let practiceJson = {};
  if (fs.existsSync(practicePath)) {
    try { practiceJson = JSON.parse(fs.readFileSync(practicePath, 'utf8')); } catch {}
  }
  const practiceExt = (loc === 'pt' || loc === 'pt-BR' || loc === 'pt-PT')
    ? practiceExtensions.pt
    : loc === 'es' ? practiceExtensions.es : practiceExtensions.en;
  Object.assign(practiceJson, practiceExt);
  fs.writeFileSync(practicePath, JSON.stringify(practiceJson, null, 2) + '\n');

  // 4. Extend dashboard.json
  const dashboardPath = path.join(dir, 'dashboard.json');
  let dashJson = {};
  if (fs.existsSync(dashboardPath)) {
    try { dashJson = JSON.parse(fs.readFileSync(dashboardPath, 'utf8')); } catch {}
  }
  const dashExt = (loc === 'pt' || loc === 'pt-BR' || loc === 'pt-PT')
    ? dashboardExtensions.pt
    : loc === 'es' ? dashboardExtensions.es : dashboardExtensions.en;
  Object.assign(dashJson, dashExt);
  fs.writeFileSync(dashboardPath, JSON.stringify(dashJson, null, 2) + '\n');

  // 5. Extend navigation.json
  const navPath = path.join(dir, 'navigation.json');
  let navJson = {};
  if (fs.existsSync(navPath)) {
    try { navJson = JSON.parse(fs.readFileSync(navPath, 'utf8')); } catch {}
  }
  const navExt = (loc === 'pt' || loc === 'pt-BR' || loc === 'pt-PT')
    ? navigationExtensions.pt
    : loc === 'es' ? navigationExtensions.es : navigationExtensions.en;
  Object.assign(navJson, navExt);
  fs.writeFileSync(navPath, JSON.stringify(navJson, null, 2) + '\n');

  console.log(`Synchronized all 5 namespaces for locale: ${loc}`);
});

